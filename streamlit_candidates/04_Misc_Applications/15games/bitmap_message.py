import streamlit as st
st.title('bitmap_message.py - 自動化展示')
st.info('這是從原專案腳本自動包裝產生的互動式介面。')

import sys

# 點陣圖的圖案
# 你可以自己修改這裡的圖案，只要用任意非空白字元填滿形狀即可。
bitmap = """
                                                                       
                   ***               ***                               
                 *******           *******                             
               ***********       ***********                           
              *************     *************                          
             ***************   ***************                         
            ***************** *****************                        
            ***********************************                        
            ***********************************                        
            ***********************************                        
             *********************************                         
              *******************************                          
               *****************************                           
                 *************************                             
                   *********************                               
                     *****************                                 
                       *************                                   
                         *********                                     
                           *****                                       
                             *                                         
                                                                       
"""

def main():
    st.write('點陣圖訊息 (Bitmap Message)')
    st.write('將你輸入的訊息，以點陣圖的形狀印出來。')
    st.write('請輸入你要顯示的訊息：')
    message = st.text_input('> ')
    
    if message == '':
        sys.exit()

    # 遍歷點陣圖中的每一行
    for line in bitmap.splitlines():
        # 遍歷這一行的每一個字元
        for i, bit in enumerate(line):
            if bit == ' ':
                # 若點陣圖該位置是空白，就印出空白（且不換行）
                st.write(' ', end='')
            else:
                # 若點陣圖該位置不是空白，則印出你輸入的訊息字元
                # 使用 i % len(message) 可以讓訊息不斷循環並對齊
                st.write(message[i % len(message)], end='')
        # 這一行印完後，印出一個換行字元
        st.write()

if __name__ == '__main__':
    main()
