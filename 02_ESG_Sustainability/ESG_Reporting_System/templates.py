@st.cache_data
def get_excel_template_bytes(template_key: str) -> bytes:
    """
    根據鍵值產出對應 GRI 指標的 Excel 模板二進位資料，採用 Streamlit 快取技術以優化重複存取速度。
    
    Args:
        template_key: 模板之唯一識別鍵名 (如 "env", "soc", "energy" ...)
        
    Returns:
        Excel 檔案二進位 bytes 內容
    """
    tpl = TEMPLATES_DATA[template_key]
    df = pd.DataFrame(tpl["rows"])
    output = io.BytesIO()
    with pd.ExcelWriter(output, engine='openpyxl') as writer:
        df.to_excel(writer, index=False, sheet_name=tpl["sheet_name"])
    return output.getvalue()
